/// `a('chave', {'n': '3'})` no idioma do app.
class AdminText {
  const AdminText(this.lang);
  final String lang;

  String call(String key, [Map<String, String> vars = const {}]) {
    var s = _kAdmin[lang]?[key] ?? _kAdmin['en']![key] ?? key;
    vars.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }
}
